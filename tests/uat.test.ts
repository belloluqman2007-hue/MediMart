type Agent = ReturnType<typeof request.agent>;

const actor = (agent: Agent, session: SessionResponse, email: string, password: string) => ({
  get: (path: string) => agent.get(path),
  post: (path: string, body: object = {}) =>
    agent.post(path).set('Origin', origin).set('X-CSRF-Token', session.csrfToken!).send(body),
  put: (path: string, body: object = {}) =>
    agent.put(path).set('Origin', origin).set('X-CSRF-Token', session.csrfToken!).send(body),
  delete: (path: string) =>
    agent.delete(path).set('Origin', origin).set('X-CSRF-Token', session.csrfToken!).send({}),
  agent,
  session,
  email,
  password,
});
type Client = ReturnType<typeof actor>;

async function staff(owner: Client, role: string, name: string): Promise<Client> {
  const email = `${role}@uat-fictional.test`;
  const password = `UAT fictional ${role} passphrase 2026!`;
  const created = await owner.post('/api/staff', {
    fullName: name,
    email,
    password,
    roles: [role],
  });
  expect(created.status, JSON.stringify(created.body)).toBe(201);
  const agent = request.agent(app);
  const login = await agent.post('/api/auth/login').set('Origin', origin).send({ email, password });
  expect(login.status, JSON.stringify(login.body)).toBe(200);
  return actor(agent, login.body, email, password);
}

