    const totals = (
      await db.all<{ net: number; gross: number }>(
        `SELECT COALESCE(SUM(total_kobo),0) AS net, COALESCE(SUM(subtotal_kobo),0) AS gross
         FROM sales WHERE status != 'voided'`,
      )
    )[0]!;
    const refundTotal = (
      await db.all<{ total: number }>(
        "SELECT COALESCE(SUM(total_reversed_kobo),0) total FROM sale_reversals WHERE reversal_type='refund'",
      )
    )[0]!.total;
    expect(refundTotal).toBeGreaterThan(0);

    // Refunds are reported separately and subtracted from takings exactly once.
    expect(finance.body.sales.refundsKobo).toBe(refundTotal);
    expect(finance.body.sales.netSalesRevenueKobo).toBe(totals.net - refundTotal);
    expect(sales.body.financials.refundsKobo).toBe(refundTotal);
    expect(sales.body.financials.salesRevenueKobo).toBe(totals.net - refundTotal);
    // Gross sales is the pre-discount subtotal of every sale that was not voided.
    expect(finance.body.sales.grossSalesKobo).toBe(totals.gross);
    expect(dashboard.body.sales.netSalesRevenueKobo).toBe(finance.body.sales.netSalesRevenueKobo);
    expect(finance.body.expenses.recordedGrossKobo).toBe(500_000);
    expect(finance.body.purchases.goodsReceivedKobo).toBeGreaterThan(0);

    // Stock value on the dashboard values batched units at their delivered cost and any unbatched
    // units at the product cost price — the same rule the valuation report documents.
    const valuation = await db.all<{ value: number }>(
      `SELECT SUM(
         COALESCE((SELECT SUM(quantity_remaining * purchase_cost_kobo) FROM product_batches
                    WHERE product_id = b.product_id), 0)
         + MAX(0, b.quantity - COALESCE((SELECT SUM(quantity_remaining) FROM product_batches
                    WHERE product_id = b.product_id), 0)) * p.purchase_cost_kobo
       ) value
       FROM stock_balances b JOIN products p ON p.id = b.product_id
       WHERE p.deleted_at IS NULL AND b.quantity > 0`,
    );
    expect(dashboard.body.inventory.stockValueCostKobo).toBe(Number(valuation[0]!.value));

    // Every sale has matching ledger entries, and the ledger sums to the stock on hand.
    const ledger = await db.all<{ product_id: string; net: number }>(
      'SELECT product_id, SUM(quantity) net FROM stock_movements GROUP BY product_id',
    );
    for (const row of ledger) expect(await qty(row.product_id)).toBe(row.net);
